import { themes, typography, space, radius, shadow, motion, type SemanticColors } from "./tokens.ts";

const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);

function colorVars(c: SemanticColors, indent: string): string {
  return Object.entries(c)
    .map(([k, v]) => `${indent}--mm-${kebab(k)}: ${v};`)
    .join("\n");
}

function shadowVars(s: Record<string, string>, indent: string): string {
  return Object.entries(s)
    .map(([k, v]) => `${indent}--mm-shadow-${k}: ${v};`)
    .join("\n");
}

/**
 * Generates the CSS custom properties consumed by the web, admin and desktop
 * (webview) apps. Theme resolution:
 *  - `data-theme="light" | "dark"` on <html> forces a theme (user setting),
 *  - otherwise the OS preference decides ("automatic" mode).
 */
export function buildCss(): string {
  const i = "  ";
  const staticVars = [
    `${i}--mm-font-display: ${typography.family.display};`,
    `${i}--mm-font-sans: ${typography.family.sans};`,
    `${i}--mm-font-mono: ${typography.family.mono};`,
    ...Object.entries(typography.size).map(([k, v]) => `${i}--mm-text-${k}: ${v};`),
    ...Object.entries(space).map(([k, v]) => `${i}--mm-space-${k}: ${v};`),
    ...Object.entries(radius).map(([k, v]) => `${i}--mm-radius-${k}: ${v};`),
    ...Object.entries(motion.duration).map(([k, v]) => `${i}--mm-duration-${k}: ${v}ms;`),
    ...Object.entries(motion.easing).map(
      ([k, v]) => `${i}--mm-ease-${k}: cubic-bezier(${v.join(", ")});`,
    ),
  ].join("\n");

  return `/* Generated by @mansomirror/design-tokens — do not edit by hand. */
:root {
${staticVars}
${colorVars(themes.light, i)}
${shadowVars(shadow.light, i)}
  color-scheme: light;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${colorVars(themes.dark, i + i)}
${shadowVars(shadow.dark, i + i)}
    color-scheme: dark;
  }
}

:root[data-theme="dark"] {
${colorVars(themes.dark, i)}
${shadowVars(shadow.dark, i)}
  color-scheme: dark;
}

@media (prefers-reduced-motion: reduce) {
  :root {
    --mm-duration-fast: 0ms;
    --mm-duration-base: 0ms;
    --mm-duration-slow: 0ms;
    --mm-duration-deliberate: 0ms;
  }
}
`;
}
